/**
 * Build js/conductivity.js — a ground-conductivity grid for the AM
 * groundwave model — from the FCC's digitized M3 map (scripts/m3.seq,
 * downloaded from https://www.fcc.gov/media/radio/m3-ground-conductivity-map).
 *
 * m3.seq is a list of boundary segments between conductivity zones:
 *   id  lat1  lonW1  lat2  lonW2  eastValue  westValue
 * (longitudes west-positive; values in mS/m, 5000 = seawater). Header rows
 * with id 9999 are a tile index and are skipped. The east/west reading of
 * the two value columns was confirmed by consistency: on every scanline,
 * the east value of each boundary matches the west value of the next
 * boundary over (9248 of 9249 adjacent pairs across the region).
 *
 * The grid is rasterized by scanline: each cell takes the east value of the
 * nearest boundary to its west. It covers every network tower plus 800 km,
 * past the longest AM reach (WNAX's FCC 0.5 mV/m contour is 388 km). Codes above 100 other than 5000 (102, 199;
 * only in northern Ontario here) are not conductivities and are stored as
 * "unknown" — the path model carries the previous value across them.
 *
 * Usage: node scripts/build-conductivity.js
 */

const fs = require('fs');

const STEP_DEG = 0.05;    // ~5 km cells
const REACH_KM = 800;     // past the longest AM tier edge in js/lib.js
const UNKNOWN = 0;        // stored for non-conductivity codes

const segs = [];
for (const line of fs.readFileSync('./scripts/m3.seq', 'utf8').split('\n')) {
  const f = line.trim().split(/\s+/).map(Number);
  if (f.length < 7 || f[0] === 9999) continue;
  segs.push({ y1: f[1], x1: -f[2], y2: f[3], x2: -f[4], east: f[5], west: f[6] });
}

const stationsSrc = fs.readFileSync('./js/stations.js', 'utf8');
const stations = JSON.parse(stationsSrc.replace(/^const stations = /, '').replace(/;\s*$/, ''));
const lats = stations.map(s => s.latitude);
const lngs = stations.map(s => s.longitude);
const padLat = REACH_KM / 111.2;
const maxLat = Math.max(...lats) + padLat;
const padLng = REACH_KM / (111.2 * Math.cos(maxLat * Math.PI / 180));
const snap = (v, fn) => fn(v / STEP_DEG) * STEP_DEG;
const south = +snap(Math.min(...lats) - padLat, Math.floor).toFixed(2);
const north = +snap(maxLat, Math.ceil).toFixed(2);
const west = +snap(Math.min(...lngs) - padLng, Math.floor).toFixed(2);
const east = +snap(Math.max(...lngs) + padLng, Math.ceil).toFixed(2);
const rows = Math.round((north - south) / STEP_DEG);
const cols = Math.round((east - west) / STEP_DEG);

const clean = v => (v > 100 && v !== 5000) ? UNKNOWN : v;
const values = [UNKNOWN];
const indexOf = v => {
  let i = values.indexOf(v);
  if (i === -1) { values.push(v); i = values.length - 1; }
  return i;
};

let agree = 0, disagree = 0;
const rowStrings = [];
for (let r = 0; r < rows; r++) {
  const y = south + (r + 0.5) * STEP_DEG;
  const xs = [];
  for (const s of segs) {
    if (!(y >= Math.min(s.y1, s.y2) && y < Math.max(s.y1, s.y2))) continue;
    xs.push({ x: s.x1 + (y - s.y1) * (s.x2 - s.x1) / (s.y2 - s.y1), east: s.east, west: s.west });
  }
  xs.sort((a, b) => a.x - b.x);
  for (let i = 0; i + 1 < xs.length; i++) {
    if (xs[i].east === xs[i + 1].west) agree++; else disagree++;
  }

  // Run-length encode: value index as a letter, run length in base 36
  let out = '', prev = -1, run = 0, k = 0;
  for (let c = 0; c < cols; c++) {
    const x = west + (c + 0.5) * STEP_DEG;
    while (k < xs.length && xs[k].x <= x) k++;
    const raw = k > 0 ? xs[k - 1].east : (xs.length ? xs[0].west : UNKNOWN);
    const idx = indexOf(clean(raw));
    if (idx === prev) run++;
    else {
      if (run) out += String.fromCharCode(65 + prev) + run.toString(36);
      prev = idx; run = 1;
    }
  }
  out += String.fromCharCode(65 + prev) + run.toString(36);
  rowStrings.push(out);
}

console.log(`Boundary consistency: ${agree} agree, ${disagree} disagree`);
console.log(`Grid ${rows} x ${cols} at ${STEP_DEG}°, ${south}..${north}N ${west}..${east}E, values ${values.join(',')}`);

const banner = `// Generated by scripts/build-conductivity.js from the FCC M3 ground-conductivity
// map (scripts/m3.seq). Do not edit by hand. Rows run south to north; each row
// is run-length encoded as <value letter><run length in base 36>, where the
// letter indexes "values" (mS/m; 0 = unknown, 5000 = seawater).
`;
const data = { south, west, step: STEP_DEG, rows, cols, values, rowData: rowStrings };
fs.writeFileSync('./js/conductivity.js', `${banner}const M3_CONDUCTIVITY = ${JSON.stringify(data)};\n`);
console.log(`✓ Wrote js/conductivity.js (${(fs.statSync('./js/conductivity.js').size / 1024).toFixed(0)} KB)`);
