#!/usr/bin/env node
/**
 * Pre-renders the full station table into stations.html so search engines and
 * AI crawlers (which don't execute JavaScript) can see every station.
 *
 * Run after any change to js/stations.js:
 *   node scripts/generate-station-table.js
 */
const fs = require('fs');
const path = require('path');

const rootDir = path.join(__dirname, '..');
const stationsSrc = fs.readFileSync(path.join(rootDir, 'js', 'stations.js'), 'utf8');
const stations = JSON.parse(stationsSrc.replace(/^const stations = /, '').replace(/;\s*$/, ''));

// Minnesota first, then the rest of the network
const stateOrder = { MN: 0, ND: 1, SD: 2, IA: 3, WI: 4 };
const stateRank = s => stateOrder[s] !== undefined ? stateOrder[s] : 9;
const sortedStations = [...stations].sort((a, b) =>
  stateRank(a.State) - stateRank(b.State) ||
  a.City.localeCompare(b.City) ||
  a.Frequency - b.Frequency);

// AM nighttime behavior flag — keep in sync with nightBehavior() in js/lib.js
function nightBehavior(station) {
  if (station.Format !== 'AM' || station.powerNight == null || station.powerNight >= station.power) {
    return null;
  }
  if (station.powerNight <= 0) {
    return {
      symbol: '☀️',
      title: 'Daytime-only AM station — off the air from sunset to sunrise, so not available during night games'
    };
  }
  const fmt = kw => kw >= 1 ? `${kw} kW` : `${Math.round(kw * 1000)} watts`;
  return {
    symbol: '🌙',
    title: `Runs reduced power after sunset (${fmt(station.power)} day → ${fmt(station.powerNight)} night) — expect a weaker signal during night games`
  };
}

let html = `
    <table class="station-table">
      <thead>
        <tr>
          <th>City</th>
          <th>State</th>
          <th>Frequency</th>
          <th>Call Sign</th>
        </tr>
      </thead>
      <tbody>
  `;

sortedStations.forEach(station => {
  const night = nightBehavior(station);
  const nightHtml = night ? ` <span class="night-flag" title="${night.title}">${night.symbol}</span>` : '';
  const callSign = station.translatorCallSign
    ? `${station.CallSign} <span class="station-role secondary" title="FM translator ${station.translatorCallSign} relaying ${station.CallSign}">translator</span>`
    : station.CallSign;

  html += `
      <tr>
        <td data-label="City:">${station.City}</td>
        <td data-label="State:">${station.State || ''}</td>
        <td data-label="Frequency:">${station.Frequency}${station.Format}${nightHtml}</td>
        <td data-label="Call Sign:">${callSign}</td>
      </tr>
    `;
});

html += `
      </tbody>
    </table>
    <div class="station-count">
      Showing ${sortedStations.length} stations
    </div>
  `;

const startMarker = '<!-- STATIC-STATIONS-START (generated by scripts/generate-station-table.js — do not edit by hand) -->';
const endMarker = '<!-- STATIC-STATIONS-END -->';

const pagePath = path.join(rootDir, 'stations.html');
const page = fs.readFileSync(pagePath, 'utf8');
const startIdx = page.indexOf(startMarker);
const endIdx = page.indexOf(endMarker);
if (startIdx === -1 || endIdx === -1) {
  console.error('Markers not found in stations.html — expected STATIC-STATIONS-START/END comments inside #stationTable');
  process.exit(1);
}

const updated = page.slice(0, startIdx + startMarker.length) + '\n' + html.trim() + '\n  ' + page.slice(endIdx);
fs.writeFileSync(pagePath, updated);
console.log(`Rendered ${sortedStations.length} station rows into stations.html`);
